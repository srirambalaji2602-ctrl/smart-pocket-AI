# PocketSmart AI

PocketSmart AI is a Generative AI based smart budget and recommendation assistant.

It provides:

- Home Interior Planner
- Party Planner
- Jewelry Planner
- Gemini AI integration
- Optional jewelry outfit image analysis
- User registration
- User login
- JWT authentication
- Recommendation history
- Marketplace search links
- SQLite database
- Responsive web interface
- FastAPI backend
- REST APIs
- Swagger documentation


